import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import {randomUUID} from 'node:crypto';
const site = process.env.EYE_LOAD_SITE, pool = process.env.EYE_LOAD_POOL;
if (!site || !pool) throw new Error('Set EYE_LOAD_SITE and EYE_LOAD_POOL from the intended setup/warm run before running a diagnostic stage.');
const base=new URL('./',import.meta.url);const {url:deployedUrl}=JSON.parse(await readFile(new URL('.state/deployment.json',base)));const {TEST_TOKEN}=JSON.parse(await readFile(new URL('.state/site-secrets.json',base)));
const url=process.env.EYE_LOAD_URL??deployedUrl;
const mode=process.argv[2]??'eye',rate=process.argv[3]??'10',duration=process.argv[4]??'5m';
const run=`${mode}-${rate}-${new Date().toISOString().replace(/[^0-9]/g,'').slice(0,14)}-${randomUUID().slice(0,8)}`;
await mkdir(new URL('results/stages/',base),{recursive:true});
const child=spawn('k6',['run','--quiet','load.js'],{cwd:base,env:{...process.env,URL:url,TEST_TOKEN,MODE:mode,RATE:rate,DURATION:duration,RUN:run,SITE:site,POOL:pool,SUMMARY:`results/stages/${run}.json`},stdio:['ignore','pipe','pipe']});
let output='';child.stdout.on('data',b=>output+=b);child.stderr.on('data',b=>output+=b);
console.log(JSON.stringify({run,mode,rate,duration,startedAt:new Date().toISOString()}));
const code=await new Promise(r=>child.on('close',r));await writeFile(new URL(`results/stages/${run}.log`,base),output);
console.log(JSON.stringify({run,code,endedAt:new Date().toISOString()}));process.exitCode=code;
